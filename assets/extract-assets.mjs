#!/usr/bin/env node
// Regenerates src/02-assets.js from two sources:
//
//   1. the product's own icon components   — point ICONS_DIR at them
//   2. anything dropped into ./brands/     — file name becomes the key
//
// Run it whenever an icon changes or a brand mark arrives, then ./build.sh.
//
// It is a script rather than shell history on purpose: the asset pipeline has to be
// re-runnable by someone who was not there the first time.

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

// ── configure these two for the target repo ──────────────────────────────────────
const ICONS_DIR = join(here, '..', '..', 'src', 'icons');   // where the product keeps icons
const ICON_FILE = 'index.tsx';                              // the file inside each icon folder

/** plugin key → folder name under ICONS_DIR. Keys are what screens call ICON() with. */
const ICONS = {
  check: 'check-circle',
  'chevron-right': 'chevron-right',
};

const BRANDS_DIR = join(here, 'brands');
const INK = '#0F0F0F';   // what currentColor resolves to; Figma imports it black otherwise

// ── normalising ──────────────────────────────────────────────────────────────────
const JSX_ATTRS = [
  ['strokeWidth', 'stroke-width'], ['strokeLinecap', 'stroke-linecap'],
  ['strokeLinejoin', 'stroke-linejoin'], ['strokeMiterlimit', 'stroke-miterlimit'],
  ['fillRule', 'fill-rule'], ['clipRule', 'clip-rule'], ['clipPath', 'clip-path'],
  ['stopColor', 'stop-color'], ['stopOpacity', 'stop-opacity'],
];

function normalise(svg, inkColour) {
  svg = svg.replace(/\bclassName=\{[^}]*\}/g, '').replace(/\bclassName="[^"]*"/g, '');
  svg = svg.replace(/strokeWidth="currentStroke"/g, 'stroke-width="1.5"');
  for (const [a, b] of JSX_ATTRS) svg = svg.split(a).join(b);
  svg = svg.replace(/\{[^}]*\}/g, '').replace(/\s+/g, ' ').trim();

  const vb = svg.match(/viewBox="([\d.\s-]+)"/);
  if (!vb) throw new Error('no viewBox');
  const [, , w, h] = vb[1].split(/\s+/);
  if (!/width=/.test(svg)) svg = svg.replace('<svg', `<svg width="${w}" height="${h}"`);
  else svg = svg.replace(/width="[^"]*"/, `width="${w}"`).replace(/height="[^"]*"/, `height="${h}"`);
  if (!/xmlns/.test(svg)) svg = svg.replace('<svg', '<svg xmlns="http://www.w3.org/2000/svg"');

  // createNodeFromSvg imports currentColor as black and rejects non-standard stroke values,
  // so both are resolved before Figma ever sees the string.
  svg = svg.split('currentColor').join(inkColour);
  return { svg, w: parseFloat(w), h: parseFloat(h) };
}

function fromComponent(folder, inkColour) {
  const file = join(ICONS_DIR, folder, ICON_FILE);
  if (!existsSync(file)) return null;
  const src = readFileSync(file, 'utf8');
  // Some icons keep their markup in a template string with the hash URL-escaped.
  const tpl = src.match(/SVG_CONTENT\s*=\s*`([\s\S]*?)`/);
  const raw = tpl ? tpl[1].split('%23').join('#') : (src.match(/<svg\b[\s\S]*?<\/svg>/) || [])[0];
  if (!raw) return null;
  return normalise(raw, inkColour);
}

// ── collect ──────────────────────────────────────────────────────────────────────
const icons = {};
const missing = [];
for (const [key, folder] of Object.entries(ICONS)) {
  const out = fromComponent(folder, '#FFFFFF');   // recoloured at use time, so the value is a placeholder
  if (out) icons[key] = out.svg; else missing.push(`icon/${key} (${folder})`);
}

// Anything dropped into ./brands/ is picked up by filename, so adding a mark needs no code
// change. Raster is allowed: some brands have been pulled from the open icon sets over
// trademark requests, and a favicon is then the only accurate mark available.
const brands = {};
const images = {};
let dropped = 0;
if (existsSync(BRANDS_DIR)) {
  for (const f of readdirSync(BRANDS_DIR)) {
    if (/\.(png|jpe?g)$/i.test(f)) {
      images[basename(f).replace(/\.(png|jpe?g)$/i, '').toLowerCase()] =
        readFileSync(join(BRANDS_DIR, f)).toString('base64');
      dropped++;
      continue;
    }
    if (!f.toLowerCase().endsWith('.svg')) continue;
    try {
      const out = normalise(readFileSync(join(BRANDS_DIR, f), 'utf8'), INK);
      brands[basename(f, '.svg').toLowerCase()] = { svg: out.svg, w: out.w, h: out.h };
      dropped++;
    } catch (e) {
      console.error(`  ! brands/${f}: ${e.message}`);
    }
  }
}

const header = [
  '// GENERATED by extract-assets.mjs — do not edit by hand.',
  '//',
  "// Icon geometry is lifted verbatim from the product's own icon source; brand marks come",
  '// from ./brands/*.svg and ./brands/*.png. currentColor is resolved here because',
  '// createNodeFromSvg would otherwise import it black, and strokeWidth="currentStroke" is',
  '// not valid SVG.',
  '',
].join('\n');

writeFileSync(join(here, 'src', '02-assets.js'),
  header +
  'const ICON_SVG = ' + JSON.stringify(icons) + ';\n\n' +
  'const BRAND_SVG = ' + JSON.stringify(brands) + ';\n\n' +
  'const BRAND_IMG = ' + JSON.stringify(images) + ';\n');

console.log(`icons ${Object.keys(icons).length}  brands ${Object.keys(brands).length} vector + ${Object.keys(images).length} raster (${dropped} from ./brands)`);
if (missing.length) console.error('missing:\n  ' + missing.join('\n  '));
